"""Keep the emulator list in README.md in sync with data/emulators.json."""

from __future__ import annotations

from . import registry

START = "<!-- EMULATORS:START (generated by `python -m tracker readme`, do not edit by hand) -->"
END = "<!-- EMULATORS:END -->"
README = registry.ROOT / "README.md"


def render(reg: registry.Registry) -> str:
    by_id = {e["id"]: e for e in reg.emulators}
    out: list[str] = []
    for cat, label in registry.CATEGORIES.items():
        items = [e for e in reg.emulators if e["category"] == cat]
        if not items:
            continue
        out += [f"#### {label} ({len(items)})", "", "| Project | Platforms | Notes |", "| :-- | :-- | :-- |"]
        for e in items:
            name = f"[{e['name']}](https://github.com/{e['repo']})"
            if e["tier"] == "featured":
                name = f"**{name}** ⭐"
            notes = []
            if e.get("forkOf") and e["forkOf"] in by_id:
                notes.append(f"Based on {by_id[e['forkOf']]['name']}")
            if e.get("summary"):
                notes.append(e["summary"].replace("|", "\\|"))
            out.append(f"| {name} | {', '.join(e.get('platforms', [])) or '—'} | {' · '.join(notes) or '—'} |")
        out.append("")
    return "\n".join(out).rstrip()


def update(reg: registry.Registry) -> bool:
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit("README.md is missing the EMULATORS markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{START}\n{render(reg)}\n{END}{tail}"
    changed = new != text
    if changed:
        README.write_text(new, encoding="utf-8")
    return changed
