"""Keep the emulator list in README.md in sync with data/emulators.json."""

from __future__ import annotations

from typing import Any

from . import registry

START = "<!-- EMULATORS:START (generated by `python -m tracker readme`, do not edit by hand) -->"
END = "<!-- EMULATORS:END -->"
README = registry.ROOT / "README.md"


def _table(items: list[dict[str, Any]], by_id: dict[str, dict[str, Any]], show_cat: bool = False) -> list[str]:
    if show_cat:
        lines = ["| Project | Category | Platforms | Notes |", "| :-- | :-- | :-- | :-- |"]
    else:
        lines = ["| Project | Platforms | Notes |", "| :-- | :-- | :-- |"]

    for e in items:
        name = f"[{e['name']}](https://github.com/{e['repo']})"
        if e["tier"] == "featured":
            name = f"**{name}** ⭐"
        notes = []
        if e.get("forkOf") and e["forkOf"] in by_id:
            notes.append(f"Based on {by_id[e['forkOf']]['name']}")
        if e.get("summary"):
            notes.append(e["summary"].replace("|", "\\|"))
        plats = ", ".join(e.get("platforms", [])) or "—"
        note_str = " · ".join(notes) or "—"
        if show_cat:
            cat = registry.CATEGORIES.get(e["category"], e["category"])
            lines.append(f"| {name} | {cat} | {plats} | {note_str} |")
        else:
            lines.append(f"| {name} | {plats} | {note_str} |")
    return lines


def render(reg: registry.Registry) -> str:
    by_id = {e["id"]: e for e in reg.emulators}
    out: list[str] = []

    featured = [e for e in reg.emulators if e["tier"] == "featured"]
    if featured:
        out += [f"### Featured ({len(featured)})", ""]
        out += _table(featured, by_id, show_cat=True)
        out.append("")

    out += [f"### Full Directory by Category ({len(reg.emulators)} total)", ""]
    for cat, label in registry.CATEGORIES.items():
        items = [e for e in reg.emulators if e["category"] == cat]
        if not items:
            continue
        out += [
            "<details>",
            f"<summary><strong>{label} ({len(items)})</strong> — expand table</summary>",
            "",
            *_table(items, by_id),
            "",
            "</details>",
            "",
        ]
    return "\n".join(out).rstrip()


def update(reg: registry.Registry) -> bool:
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit("README.md is missing the EMULATORS markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{START}\n{render(reg)}\n{END}{tail}"
    changed = new != text
    if changed:
        README.write_text(new, encoding="utf-8")
    return changed
